// Generates components/icons/generated.tsx from the Keyline icon set
// (rounded, stroke variant). Add a name to ICONS and run `npm run icons`.
import { createRequire } from 'node:module'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const require = createRequire(import.meta.url)
const { icons } = require('@iconify-json/keyline-icons/icons.json')

const ICONS = [
  // Arrows and chevrons
  'arrow-right', 'arrow-left', 'arrow-up', 'arrow-down', 'arrow-up-right', 'arrow-down-right',
  'arrow-up-down', 'arrow-left-right', 'chevron-right', 'chevron-left', 'chevron-down', 'chevron-up',
  'chevrons-up-down',
  // Controls
  'x', 'menu', 'plus', 'minus', 'check', 'more-horizontal', 'search', 'filter', 'sliders-horizontal',
  'settings', 'copy', 'download', 'upload', 'cloud-upload', 'refresh-cw', 'rotate-ccw', 'undo',
  'history', 'repeat', 'panel-left', 'panel-left-close', 'panel-left-open', 'link', 'share', 'bin',
  'grip-vertical', 'cursor-click', 'mouse-pointer',
  // Status
  'eye', 'eye-off', 'info', 'circle-question', 'circle-alert', 'triangle-alert', 'circle-check',
  'circle-x', 'badge-check', 'loader-circle', 'lock', 'key', 'shield', 'shield-check', 'bell',
  // Theme and people
  'sun', 'moon', 'user', 'mail', 'send', 'globe', 'language', 'house', 'star', 'heart', 'sparkles',
  'zap', 'flame', 'lightbulb', 'rocket', 'gift', 'flag', 'bookmark', 'tag',
  // Time
  'clock', 'timer', 'hourglass', 'calendar', 'calendar-days', 'calendar-check',
  // Layout and files
  'target', 'layers', 'list', 'table', 'grid-2x2', 'layout-dashboard', 'layout-bento', 'wrench',
  'book-open', 'newspaper', 'file', 'file-text', 'file-spreadsheet', 'file-check', 'file-x',
  'file-arrow-up', 'folder', 'database', 'server-off', 'cloud-off', 'cookie', 'scan', 'git-merge',
  'split', 'package', 'box', 'hash', 'sigma', 'calculator', 'gauge',
  // Money and charts
  'hand-coins', 'coins', 'banknote', 'wallet', 'piggy-bank', 'landmark', 'building', 'briefcase',
  'receipt', 'percent', 'scale', 'dollar-sign', 'euro', 'pound-sterling', 'swiss-franc',
  'circle-dollar-sign', 'trending-up', 'trending-down', 'activity', 'chart-pie', 'chart-bar',
  'chart-column', 'chart-column-stacked', 'chart-line', 'chart-area', 'chart-candlestick',
  'chart-spline', 'bar-chart',
]

const pascal = (name) => name.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('')

const toJsx = (body) =>
  body
    // Stroke styling lives on the <svg> root so one prop controls it.
    .replace(/ stroke-width="[^"]*"/g, '')
    .replace(/ stroke-linecap="round"/g, '')
    .replace(/ stroke-linejoin="round"/g, '')
    .replace(/ fill="none" stroke="currentColor"/g, '')
    .replace(/fill-rule=/g, 'fillRule=')
    .replace(/clip-rule=/g, 'clipRule=')
    .replace(/stroke-linecap=/g, 'strokeLinecap=')
    .replace(/stroke-linejoin=/g, 'strokeLinejoin=')

const missing = ICONS.filter((name) => !icons[name])
if (missing.length) {
  console.error(`Not in the icon set: ${missing.join(', ')}`)
  process.exit(1)
}

const lines = [
  '// Generated by scripts/generate-icons.mjs from Keyline Icons (MIT). Do not edit by hand.',
  "import { createIcon } from './icon'",
  '',
  ...[...new Set(ICONS)].sort().map(
    (name) => `export const ${pascal(name)} = createIcon('${pascal(name)}', <>${toJsx(icons[name].body)}</>)`
  ),
  '',
]

const out = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'components', 'icons', 'generated.tsx')
writeFileSync(out, lines.join('\n'))
console.log(`${ICONS.length} icons -> components/icons/generated.tsx`)
